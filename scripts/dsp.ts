// Builds the DSP core. `bun run dsp`:
//   1. writes `dsp/src/ops.rs` from the tables in `src/sound/protocol.ts` (the protocol's one source);
//   2. builds the crate for `wasm32-unknown-unknown` (release);
//   3. writes `src/sound/core.gen.ts`: the module as base64, the worklet processor's source as a string, and the
//      hash of everything the build read.
// The build is committed, so a game needs no Rust toolchain and no asset or server configuration.
// `test/rules/dsp-fresh.test.ts` fails when the sources and the committed hash part. `core.gen.ts` is never merged
// by hand: run this on the merged tree.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  COMMANDS,
  ENUMS,
  EVENTS,
  type FieldType,
  FX_PARAMS,
  GEN_PARAMS,
  LIMITS,
  type OpDef,
} from "../src/sound/protocol";

const ROOT = join(import.meta.dir, "..");
const OPS_RS = "dsp/src/ops.rs";
const PROCESSOR = "src/sound/worklet/processor.js";
const CORE_GEN = "src/sound/core.gen.ts";
const WASM = "dsp/target/wasm32-unknown-unknown/release/watchpot_dsp.wasm";

const lf = (text: string) => text.replace(/\r\n/g, "\n");
const snake = (name: string) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const pascal = (name: string) =>
  name
    .toLowerCase()
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const rustType = (type: FieldType) => (typeof type === "string" ? type : `[${type[0]}; ${type[1]}]`);
const countOf = (type: FieldType) => (typeof type === "string" ? 1 : type[1]);
const scalarOf = (type: FieldType) => (typeof type === "string" ? type : type[0]);

function record(name: string, def: OpDef): string {
  const struct = pascal(name);
  const fields = Object.entries(def.fields);
  let at = 4;
  const reads: string[] = [];
  const writes: string[] = [];
  for (const [field, type] of fields) {
    const f = snake(field);
    const s = scalarOf(type);
    if (typeof type === "string") {
      reads.push(`            ${f}: ${s}_at(record, ${at}),`);
      writes.push(`        put_${s}(out, ${at}, self.${f});`);
    } else {
      reads.push(`            ${f}: core::array::from_fn(|i| ${s}_at(record, ${at} + 4 * i)),`);
      writes.push(`        for (i, v) in self.${f}.iter().enumerate() {`);
      writes.push(`            put_${s}(out, ${at} + 4 * i, *v);`);
      writes.push("        }");
    }
    at += 4 * countOf(type);
  }
  return [
    "#[derive(Clone, Copy, Debug, PartialEq)]",
    `pub struct ${struct} {`,
    ...fields.map(([field, type]) => `    pub ${snake(field)}: ${rustType(type)},`),
    "}",
    "",
    `impl Record for ${struct} {`,
    `    const OP: u16 = ${def.id};`,
    `    const SIZE: usize = ${at};`,
    "",
    "    fn read(record: &[u8]) -> Option<Self> {",
    "        if record.len() < Self::SIZE {",
    "            return None;",
    "        }",
    "        Some(Self {",
    ...reads,
    "        })",
    "    }",
    "",
    "    fn write(&self, out: &mut [u8]) {",
    "        put_u16(out, 0, Self::OP);",
    "        put_u16(out, 2, Self::SIZE as u16);",
    ...writes,
    "    }",
    "}",
    "",
  ].join("\n");
}

const ids = (name: string, table: Readonly<Record<string, OpDef>>) =>
  [
    `pub mod ${name} {`,
    ...Object.entries(table).map(([op, def]) => `    pub const ${op}: u16 = ${def.id};`),
    "}",
    "",
  ].join("\n");

/** The text of `dsp/src/ops.rs` for the protocol as it stands. */
export function opsRs(): string {
  return [
    "// Generated by `bun run dsp` from src/sound/protocol.ts. Do not edit: change the protocol and run it again.",
    "#![allow(dead_code)]",
    "",
    ...Object.entries(LIMITS).map(([name, value]) => `pub const ${name}: usize = ${value};`),
    "",
    "/// The bytes of a record's header: `u16 op, u16 byteLength`.",
    "pub const HEADER: usize = 4;",
    "",
    "#[inline]",
    "pub fn u32_at(b: &[u8], at: usize) -> u32 {",
    "    u32::from_le_bytes([b[at], b[at + 1], b[at + 2], b[at + 3]])",
    "}",
    "",
    "#[inline]",
    "pub fn f32_at(b: &[u8], at: usize) -> f32 {",
    "    f32::from_bits(u32_at(b, at))",
    "}",
    "",
    "#[inline]",
    "fn put_u16(b: &mut [u8], at: usize, v: u16) {",
    "    b[at..at + 2].copy_from_slice(&v.to_le_bytes());",
    "}",
    "",
    "#[inline]",
    "fn put_u32(b: &mut [u8], at: usize, v: u32) {",
    "    b[at..at + 4].copy_from_slice(&v.to_le_bytes());",
    "}",
    "",
    "#[inline]",
    "fn put_f32(b: &mut [u8], at: usize, v: f32) {",
    "    put_u32(b, at, v.to_bits());",
    "}",
    "",
    "/// One record of the protocol: a command or an event, header included.",
    "pub trait Record: Sized {",
    "    const OP: u16;",
    "    /// The whole record in bytes.",
    "    const SIZE: usize;",
    "    /// Reads a record; `None` when `record` is shorter than `SIZE`.",
    "    fn read(record: &[u8]) -> Option<Self>;",
    "    /// Writes the record into the first `SIZE` bytes of `out`.",
    "    fn write(&self, out: &mut [u8]);",
    "    /// The record as bytes. Allocates: for tests and offline use.",
    "    fn bytes(&self) -> Vec<u8> {",
    "        let mut out = vec![0; Self::SIZE];",
    "        self.write(&mut out);",
    "        out",
    "    }",
    "}",
    "",
    ...Object.entries(ENUMS).map(([name, values]) =>
      [
        `pub mod ${name.toLowerCase()} {`,
        ...Object.entries(values).map(
          ([key, value]) => `    pub const ${key.toUpperCase()}: u32 = ${value};`,
        ),
        "}",
        "",
      ].join("\n"),
    ),
    "/// Each effect's parameter ids.",
    "pub mod fx_param {",
    ...Object.entries(FX_PARAMS).flatMap(([kind, params]) => [
      `    pub mod ${kind} {`,
      ...Object.entries(params).map(
        ([key, value]) => `        pub const ${snake(key).toUpperCase()}: u16 = ${value};`,
      ),
      "    }",
    ]),
    "}",
    "",
    "/// Each generator's parameter ids.",
    "pub mod gen_param {",
    ...Object.entries(GEN_PARAMS).flatMap(([kind, params]) => [
      `    pub mod ${kind} {`,
      ...Object.entries(params).map(
        ([key, value]) => `        pub const ${snake(key).toUpperCase()}: u32 = ${value};`,
      ),
      "    }",
    ]),
    "}",
    "",
    "/// Command ops: shell to core.",
    ids("cmd", COMMANDS),
    "/// Event ops: core to shell.",
    ids("evt", EVENTS),
    ...Object.entries(COMMANDS).map(([name, def]) => record(name, def)),
    ...Object.entries(EVENTS).map(([name, def]) => record(name, def)),
  ]
    .join("\n")
    .replace(/\n+$/, "\n");
}

function walk(dir: string): string[] {
  return readdirSync(join(ROOT, dir), { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? walk(`${dir}/${e.name}`) : [`${dir}/${e.name}`]))
    .sort();
}

/** SHA-256 of everything the build reads: the crate, the protocol and the processor, line endings normalised. */
export function coreHash(): string {
  const hash = createHash("sha256");
  for (const path of ["dsp/Cargo.toml", ...walk("dsp/src"), "src/sound/protocol.ts", PROCESSOR]) {
    hash.update(`${path}\0${lf(readFileSync(join(ROOT, path), "utf8"))}\0`);
  }
  return hash.digest("hex");
}

/** The processor's source as the worklet gets it: the limits it is built to, then the file. */
export const processorSource = () =>
  `const LIMITS = ${JSON.stringify(LIMITS)};\n${lf(readFileSync(join(ROOT, PROCESSOR), "utf8"))}`;

function build(): void {
  const ops = opsRs();
  let onDisk = "";
  try {
    onDisk = lf(readFileSync(join(ROOT, OPS_RS), "utf8"));
  } catch {
    // First build: no ops.rs yet.
  }
  if (onDisk !== ops) writeFileSync(join(ROOT, OPS_RS), ops);

  const cargo = Bun.spawnSync(
    [
      "cargo",
      "build",
      "--release",
      "--target",
      "wasm32-unknown-unknown",
      "--manifest-path",
      "dsp/Cargo.toml",
    ],
    { cwd: ROOT, stdout: "inherit", stderr: "inherit" },
  );
  if (cargo.exitCode !== 0) process.exit(cargo.exitCode ?? 1);

  const wasm = readFileSync(join(ROOT, WASM));
  const text = [
    "// Generated by `bun run dsp`. Do not edit, and never merge by hand: run `bun run dsp` on the merged tree.",
    "/** SHA-256 of the crate, the protocol and the processor this was built from. */",
    `export const CORE_HASH: string = "${coreHash()}";`,
    "/** The worklet processor: plain JavaScript, added to the AudioWorklet from a Blob URL. */",
    `export const PROCESSOR_SOURCE: string = ${JSON.stringify(processorSource())};`,
    "/** The DSP core: `dsp/` built for wasm32-unknown-unknown, as base64. */",
    `export const CORE_BASE64: string = "${wasm.toString("base64")}";`,
    "",
  ].join("\n");
  writeFileSync(join(ROOT, CORE_GEN), text);
  console.log(
    `dsp: core ${(wasm.length / 1024).toFixed(1)} KB wasm, ${(text.length / 1024).toFixed(1)} KB in ${CORE_GEN}`,
  );
}

if (import.meta.main) build();
